    def call(self, endpoint_id: str, *, full: bool = False, **kwargs: Any) -> Any:
        '''Call by endpoint id, e.g. call("home-002", classesId=...).'''
        endpoint = _ENDPOINTS.get(endpoint_id)
        if endpoint is None:
            raise KeyError(f'unknown endpoint id: {endpoint_id}')
        params = dict(endpoint.params)
        json_body = endpoint.json_body
        form_body = dict(endpoint.form_body) if endpoint.form_body else None
        files = dict(endpoint.files) if endpoint.files else None

        params_override = kwargs.pop('params', None)
        if params_override:
            params.update(params_override)
        if 'json_body' in kwargs:
            json_body = kwargs.pop('json_body')
        if 'json' in kwargs:
            json_body = kwargs.pop('json')
        if 'form_body' in kwargs:
            form_body = kwargs.pop('form_body')
        if 'files' in kwargs:
            files = kwargs.pop('files')

        for key, value in kwargs.items():
            params[key] = value
            if isinstance(json_body, dict):
                json_body[key] = value
            if isinstance(form_body, dict):
                form_body[key] = value
            self._set_context(key, value)

        if endpoint.client == 'ttlock' and not self.context.get('ttlock_access_token'):
            self.login_ttlock()

        temp = Endpoint(
            id=endpoint.id,
            method=endpoint.method,
            path=endpoint.path,
            params=params,
            json_body=json_body,
            form_body=form_body,
            files=files,
            auth=endpoint.auth,
            base=endpoint.base,
            client=endpoint.client,
            description=endpoint.description,
            source=endpoint.source,
            headers=endpoint.headers,
            stream=endpoint.stream,
            executable=endpoint.executable,
        )
        spec = self.prepare(temp)
        response = self.execute(spec)
        if spec.stream:
            return response
        try:
            body = response.json()
        except ValueError:
            return response.text
        if isinstance(body, dict) and body.get('code') not in (None, 0):
            print(body)
            raise ApiError(
                f"code={body.get('code')} message={body.get('message')} detail={body.get('detailMessage')}",
                response.status_code,
                body,
            )
        if full:
            return body
        if isinstance(body, dict) and 'data' in body:
            return body['data']
        return body

